#include "FOW/FOWUpscaler.h"
#include "FOW/FOWTileMap.h"


FFOWUpscaler::FFOWUpscaler(int32 InSourceSize)
	: SourceSize(InSourceSize), UpscaledSize(InSourceSize * ScaleFactor)
{
	UpscaledBuffer = new uint8[UpscaledSize * UpscaledSize];
	FMemory::Memzero(UpscaledBuffer, UpscaledSize * UpscaledSize);
}

FFOWUpscaler::~FFOWUpscaler()
{
	if (UpscaledBuffer)
	{
		delete[] UpscaledBuffer;
		UpscaledBuffer = nullptr;
	}
}

void FFOWUpscaler::Upscale(const AFOWTileMap* TileMap)
{
	FMemory::Memzero(UpscaledBuffer, UpscaledSize * UpscaledSize);
	
	for (int32 Y = 0; Y < SourceSize; Y++)
	{
		for (int32 X = 0; X < SourceSize; X++)
		{
			const FTile* TileTL = TileMap->GetTile(X, Y);
			const FTile* TileTR = TileMap->GetTile(X + 1, Y);
			const FTile* TileBL = TileMap->GetTile(X, Y + 1);
			const FTile* TileBR = TileMap->GetTile(X + 1, Y + 1);
			
			bool TL = TileTL && TileTL->bIsVisible;
			bool TR = TileTR && TileTR->bIsVisible;
			bool BL = TileBL && TileBL->bIsVisible;
			bool BR = TileBR && TileBR->bIsVisible;
			
			//
			int32 CaseIndex = (TL ? 8 : 0) | (TR ? 4 : 0) | (BL ? 2 : 0) | (BR ? 1 : 0);;
			
			int32 BaseX = X * ScaleFactor;
			int32 BaseY = Y * ScaleFactor;
			
			for (int32 DY = 0; DY < ScaleFactor; DY++)
			{
				for (int32 DX = 0; DX < ScaleFactor; DX++)
				{
					int32 DestX = BaseX + DX;
					int32 DestY = BaseY + DY;

					if (DestX < UpscaledSize && DestY < UpscaledSize)
					{
						UpscaledBuffer[DestY * UpscaledSize + DestX] = MarchingPatterns[CaseIndex][DY][DX];
					}
				}
			}
		}
	}
}

